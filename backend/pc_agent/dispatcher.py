# Dispatches cloud-delegated tasks to local Windows tools and GUI automation.

import sys
import os
import traceback
from typing import Tuple

# Ensure backend path is on sys.path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from logger import get_logger
from llm.tools import TOOL_HANDLERS

TOOL_MAP = TOOL_HANDLERS

_log = get_logger(__name__)
print = _log.info


def execute_local_task(action: str, params: dict) -> Tuple[bool, str]:
    """Executes a requested action locally on the Windows desktop.
    Returns: (success: bool, message: str)
    """
    # If received via generic cloud dispatch, unpack real action and parameters
    orig_act = (action or "").strip()
    if orig_act.lower() == "jarvis_command":
        real_action = params.get("_cloud_action", "")
        cloud_params = params.get("_cloud_params", {})
        original_text = params.get("_original_text", "")
        if real_action and real_action.lower() not in ("jarvis_command", "none"):
            action = real_action
            if isinstance(cloud_params, dict):
                params = {**cloud_params, "_original_text": original_text}

    # Normalize action names generated by LLM
    act = (action or "").lower().strip()
    if act in ("set_volume", "adjust_volume", "change_volume", "volume"):
        act = "volume_set"
    elif act in ("launch_app", "start_app", "run_app"):
        act = "open_app"
    elif act in ("play_youtube", "youtube_play"):
        act = "play_media"
        if "app" not in params:
            params["app"] = "youtube"
    elif act in ("play_song", "play_music", "play_media", "play_video",
                 "play_spotify", "spotify_play"):
        act = "play_media"
        # DON'T override the app — let the LLM's choice come through
    elif act in ("pc_status_check", "status_check", "get_status"):
        act = "pc_status"
    elif act in ("send_whatsapp", "whatsapp_message", "whatsapp"):
        act = "whatsapp_send"
    elif act in ("lock", "shutdown", "restart", "sleep"):
        params["action"] = act
        act = "system_power"
    elif act in ("read_folder", "list_folder", "browse_folder", "open_folder",
                 "folder_contents", "read_directory", "list_directory"):
        act = "summarize_file"

    # Security gate: Level 4 destructive actions require desktop confirmation
    if act == "system_power" and params.get("action") in ("shutdown", "restart"):
        return False, "Shutdown and restart require the Jarvis desktop application for password verification, boss."

    print(f"[PCAgent Dispatcher] Executing action '{act}' (original '{action}') with params {params}...")

    try:
        # 1. Normalized App Launching
        if act == "open_app":
            app_name = params.get("app") or params.get("app_name") or ""
            if not app_name:
                return False, "No app name was specified, boss."
            func = TOOL_MAP.get("open_app")
            if func:
                launch_params = dict(params)
                launch_params["app"] = app_name
                launch_params["app_name"] = app_name
                res = func(launch_params)
                return True, str(res)
            return False, "App launcher tool not available."

        # 1b. Smart Media Playback (YouTube, Spotify, etc.)
        elif act == "play_media":
            query = (params.get("query") or params.get("song") or
                     params.get("media") or params.get("search") or
                     params.get("name") or "").strip()
            app = (params.get("app") or params.get("platform") or "").lower().strip()

            # Spotify handling
            if app in ("spotify", "spot"):
                import subprocess
                if query:
                    # Open Spotify with search
                    import urllib.parse
                    spotify_uri = f"spotify:search:{urllib.parse.quote_plus(query)}"
                    try:
                        os.startfile(spotify_uri)
                        return True, f"Searching for '{query}' on Spotify, boss."
                    except Exception:
                        # Fallback: open Spotify desktop app
                        subprocess.Popen(["spotify"], shell=True)
                        return True, f"Opened Spotify, boss. Search for '{query}' manually."
                else:
                    try:
                        os.startfile("spotify:")
                    except Exception:
                        subprocess.Popen(["spotify"], shell=True)
                    return True, "Opening Spotify, boss."

            # YouTube handling (default for music)
            else:
                yt_func = TOOL_MAP.get("youtube_play")
                if yt_func:
                    res = yt_func({"query": query, "browser": params.get("browser", "")})
                    return True, str(res)
                # Fallback: open YouTube search
                if query:
                    import urllib.parse
                    url = "https://www.youtube.com/results?search_query=" + urllib.parse.quote(query)
                else:
                    url = "https://www.youtube.com"
                import webbrowser
                webbrowser.open(url)
                return True, f"Playing {query} on YouTube, boss." if query else "Opening YouTube, boss."

        # 2. WhatsApp Messaging
        elif act == "whatsapp_send":
            contact = params.get("contact") or params.get("recipient") or ""
            message = params.get("message") or ""
            phone = params.get("phone") or ""
            func = TOOL_MAP.get("whatsapp_message")
            if func:
                res = func({"contact": contact, "message": message, "phone": phone})
                return True, str(res)
            return False, "WhatsApp tool not available."

        # 3. WhatsApp Calling
        elif act in ("whatsapp_call", "whatsapp_video_call"):
            contact = params.get("contact") or params.get("recipient") or ""
            call_type = "video" if "video" in act else "voice"
            func = TOOL_MAP.get("whatsapp_call")
            if func:
                res = func({"contact": contact, "call_type": call_type})
                return True, str(res)
            return False, "WhatsApp call tool not available."

        # 4. Volume Control
        elif act.startswith("volume_"):
            sub_action = act.replace("volume_", "")  # set, up, down, mute
            func = TOOL_MAP.get("volume_control")
            if func:
                payload = {"action": sub_action}
                if "level" in params:
                    payload["level"] = params["level"]
                res = func(payload)
                return True, str(res)
            return False, "Volume control tool not available."

        # 5. Media Control (Play/Pause/Skip)
        elif act.startswith("media_"):
            sub_action = act.replace("media_", "")  # play, pause, next, previous
            func = TOOL_MAP.get("media_control")
            if func:
                res = func({"action": sub_action})
                return True, str(res)
            return False, "Media control tool not available."

        # 6. System Power (Lock, Sleep, Shutdown)
        elif act in ("system_power", "lock_pc"):
            power_act = "lock" if act == "lock_pc" else params.get("action", "lock")
            func = TOOL_MAP.get("system_power")
            if func:
                res = func({"action": power_act})
                return True, str(res)
            return False, "System power tool not available."

        # 7. PC Status & Telemetry
        elif act in ("pc_status", "system_status", "status", "system_health", "check_status"):
            import psutil
            cpu = psutil.cpu_percent(interval=0.1)
            ram = psutil.virtual_memory().percent
            battery = psutil.sensors_battery()
            bat_str = f", battery at {battery.percent}%" if battery else ""
            status_msg = f"PC is running normally, sir. CPU at {cpu}%, memory at {ram}%{bat_str}."
            return True, status_msg

        # 8. File & Desktop Project / Folder Reading & Summarization
        elif act in ("summarize_file", "read_file", "doc_reader", "summarize", "read_doc"):
            filename = (params.get("file") or params.get("filename") or
                       params.get("name") or params.get("folder") or
                       params.get("folder_name") or params.get("directory") or
                       params.get("path") or "")
            location = (params.get("location") or "desktop").lower()
            original_text = params.get("_original_text", "").lower()
            target_dir = os.path.expanduser("~/Desktop") if "desktop" in location else os.path.expanduser("~/Downloads")
            matched_path = None
            if os.path.exists(target_dir):
                for root, dirs, files in os.walk(target_dir):
                    for f in files:
                        if filename.lower() in f.lower():
                            matched_path = os.path.join(root, f)
                            break
                    if matched_path:
                        break
                    for d in dirs:
                        if filename.lower() in d.lower():
                            matched_path = os.path.join(root, d)
                            break
                    if matched_path:
                        break

            if not matched_path:
                return False, f"Could not find '{filename}' on your {location}, sir."

            if os.path.isdir(matched_path):
                # Found a folder — read and summarize its key documents
                items = os.listdir(matched_path)
                readable_exts = (".pdf", ".docx", ".doc", ".txt", ".md", ".py", ".js",
                                ".html", ".css", ".json", ".csv", ".java", ".cpp", ".c")

                # Collect readable files
                readable_files = []
                for item in items:
                    item_path = os.path.join(matched_path, item)
                    if os.path.isfile(item_path) and any(item.lower().endswith(ext) for ext in readable_exts):
                        readable_files.append((item, item_path))

                # If user wants to READ/EXPLAIN/SUMMARIZE, actually read the content
                wants_content = any(w in original_text for w in (
                    "read", "explain", "summarize", "summary", "tell", "about",
                    "content", "what", "synopsis", "describe", "detail"
                ))

                if wants_content and readable_files:
                    # Read up to 3 most important files (prioritize PDFs, docs)
                    priority_order = [".pdf", ".docx", ".doc", ".md", ".txt"]
                    sorted_files = sorted(readable_files, key=lambda x: next(
                        (i for i, ext in enumerate(priority_order) if x[0].lower().endswith(ext)), 99
                    ))

                    summaries = []
                    for fname, fpath in sorted_files[:3]:
                        try:
                            from tools.doc_reader import doc_reader as _doc_reader
                            result = _doc_reader({"path": fpath})
                            summaries.append(f"📄 **{fname}**:\n{result}")
                        except Exception as e:
                            # Try raw text read as fallback
                            try:
                                with open(fpath, "r", encoding="utf-8", errors="ignore") as f:
                                    content = f.read(2000)
                                summaries.append(f"📄 **{fname}**:\n{content[:500]}...")
                            except Exception:
                                summaries.append(f"📄 **{fname}**: Could not read ({e})")

                    if summaries:
                        all_files_list = ", ".join(items[:10])
                        if len(items) > 10:
                            all_files_list += f" ...and {len(items) - 10} more"
                        header = f"Found '{filename}' folder with {len(items)} items ({all_files_list}).\n\n"
                        content_summary = "\n\n".join(summaries)
                        return True, header + content_summary

                # Fallback: just list files with details
                details = []
                for item in items[:20]:
                    item_path = os.path.join(matched_path, item)
                    if os.path.isdir(item_path):
                        sub_count = len(os.listdir(item_path)) if os.path.exists(item_path) else 0
                        details.append(f"📁 {item}/ ({sub_count} items)")
                    else:
                        size = os.path.getsize(item_path)
                        if size > 1048576:
                            details.append(f"📄 {item} ({size/1048576:.1f} MB)")
                        elif size > 1024:
                            details.append(f"📄 {item} ({size/1024:.1f} KB)")
                        else:
                            details.append(f"📄 {item} ({size} B)")
                listing = "\n".join(details)
                extra = f"\n...and {len(items) - 20} more items." if len(items) > 20 else ""
                return True, f"Found '{filename}' folder on your {location} with {len(items)} items:\n{listing}{extra}"
            else:
                # Single file — read and summarize it
                try:
                    from tools.doc_reader import doc_reader as _doc_reader
                    res = _doc_reader({"path": matched_path})
                    return True, str(res)
                except Exception:
                    with open(matched_path, "r", encoding="utf-8", errors="ignore") as f:
                        content = f.read(2000)
                    return True, f"Contents of {filename}:\n{content[:1000]}"

        # 9. Create Folder / File
        elif act in ("create_folder", "make_folder", "new_folder", "mkdir",
                     "create_directory", "make_directory"):
            name = params.get("name") or params.get("folder") or params.get("folder_name") or ""
            location = (params.get("location") or "desktop").lower()
            base = os.path.expanduser("~/Desktop") if "desktop" in location else os.path.expanduser("~/Downloads")
            if not name:
                return False, "No folder name specified, boss."
            folder_path = os.path.join(base, name)
            os.makedirs(folder_path, exist_ok=True)
            return True, f"Created folder '{name}' on your {location}, sir."

        elif act in ("create_file", "make_file", "new_file", "touch"):
            name = params.get("name") or params.get("file") or params.get("filename") or ""
            content = params.get("content") or ""
            location = (params.get("location") or "desktop").lower()
            base = os.path.expanduser("~/Desktop") if "desktop" in location else os.path.expanduser("~/Downloads")
            if not name:
                return False, "No file name specified, boss."
            file_path = os.path.join(base, name)
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(content)
            return True, f"Created file '{name}' on your {location}, sir."

        # 10. Delete File / Folder
        elif act in ("delete_folder", "remove_folder", "delete_directory", "rmdir",
                     "delete_file", "remove_file", "delete", "remove"):
            import shutil
            name = params.get("name") or params.get("file") or params.get("folder") or ""
            location = (params.get("location") or "desktop").lower()
            base = os.path.expanduser("~/Desktop") if "desktop" in location else os.path.expanduser("~/Downloads")
            if not name:
                return False, "No name specified for deletion, boss."
            target = os.path.join(base, name)
            if not os.path.exists(target):
                return False, f"'{name}' not found on your {location}, sir."
            if os.path.isdir(target):
                shutil.rmtree(target)
                return True, f"Deleted folder '{name}' from your {location}, sir."
            else:
                os.remove(target)
                return True, f"Deleted file '{name}' from your {location}, sir."

        # 11. Rename File / Folder
        elif act in ("rename_file", "rename_folder", "rename"):
            old_name = params.get("name") or params.get("old_name") or params.get("file") or ""
            new_name = params.get("new_name") or params.get("to") or ""
            location = (params.get("location") or "desktop").lower()
            base = os.path.expanduser("~/Desktop") if "desktop" in location else os.path.expanduser("~/Downloads")
            if not old_name or not new_name:
                return False, "Need both old and new names for rename, boss."
            old_path = os.path.join(base, old_name)
            new_path = os.path.join(base, new_name)
            if not os.path.exists(old_path):
                return False, f"'{old_name}' not found on your {location}, sir."
            os.rename(old_path, new_path)
            return True, f"Renamed '{old_name}' to '{new_name}' on your {location}, sir."

        # 12. Move / Copy File
        elif act in ("move_file", "move_folder", "move"):
            import shutil
            name = params.get("name") or params.get("file") or params.get("folder") or ""
            dest = params.get("destination") or params.get("to") or ""
            location = (params.get("location") or "desktop").lower()
            base = os.path.expanduser("~/Desktop") if "desktop" in location else os.path.expanduser("~/Downloads")
            if not name:
                return False, "No file/folder name specified, boss."
            src = os.path.join(base, name)
            if not os.path.exists(src):
                return False, f"'{name}' not found on your {location}, sir."
            shutil.move(src, dest)
            return True, f"Moved '{name}' to '{dest}', sir."

        elif act in ("copy_file", "copy_folder", "copy"):
            import shutil
            name = params.get("name") or params.get("file") or params.get("folder") or ""
            dest = params.get("destination") or params.get("to") or ""
            location = (params.get("location") or "desktop").lower()
            base = os.path.expanduser("~/Desktop") if "desktop" in location else os.path.expanduser("~/Downloads")
            if not name:
                return False, "No file/folder name specified, boss."
            src = os.path.join(base, name)
            if not os.path.exists(src):
                return False, f"'{name}' not found on your {location}, sir."
            if os.path.isdir(src):
                shutil.copytree(src, dest)
            else:
                shutil.copy2(src, dest)
            return True, f"Copied '{name}' to '{dest}', sir."

        # 13. Take Screenshot
        elif act in ("screenshot", "take_screenshot", "capture_screen", "screen_capture"):
            try:
                from tools.screenshot import take_screenshot
                res = take_screenshot(params)
                return True, str(res)
            except Exception as e:
                return False, f"Screenshot failed: {e}"

        # 14. Web Search
        elif act in ("web_search", "search", "google", "search_web", "internet_search"):
            query = params.get("query") or params.get("text") or params.get("q") or ""
            if not query:
                return False, "No search query specified, boss."
            func = TOOL_MAP.get("web_search") or TOOL_MAP.get("search")
            if func:
                res = func({"query": query})
                return True, str(res)
            return False, "Web search tool not available."

        # 15. Run Shell Command
        elif act in ("run_command", "execute_command", "shell", "cmd", "terminal",
                     "run_script", "execute_script"):
            import subprocess
            command = params.get("command") or params.get("cmd") or params.get("script") or ""
            if not command:
                return False, "No command specified, boss."
            result = subprocess.run(command, shell=True, capture_output=True, text=True, timeout=30)
            output = result.stdout.strip() or result.stderr.strip() or "Command completed."
            return result.returncode == 0, output[:500]

        # 16. Close Application
        elif act in ("close_app", "kill_app", "stop_app", "terminate_app", "quit_app"):
            app_name = params.get("app") or params.get("app_name") or params.get("name") or ""
            if not app_name:
                return False, "No app name specified, boss."
            func = TOOL_MAP.get("close_app")
            if func:
                res = func({"app": app_name, "app_name": app_name})
                return True, str(res)
            # Fallback: try taskkill
            import subprocess
            subprocess.run(f"taskkill /f /im {app_name}.exe", shell=True, capture_output=True)
            return True, f"Closed {app_name}, sir."

        # 17. Generic Fallback to TOOL_MAP
        elif act in TOOL_MAP:
            func = TOOL_MAP[act]
            res = func(params)
            return True, str(res)

        # 18. Smart Fallback: Use the local Jarvis brain to handle any unknown command
        else:
            original_text = params.get("_original_text", "")
            if original_text:
                return _smart_fallback(act, original_text, params)
            return False, f"Unknown PC action '{action}', boss. Try rephrasing your command."

    except Exception as e:
        err = traceback.format_exc()
        print(f"[PCAgent Dispatcher] Error running '{action}': {err}")
        return False, f"Failed to run '{action}' on PC: {str(e)}"
    finally:
        try:
            from security.audit_log import log_action
            log_action({
                "source": "pc_agent_remote",
                "tool": action,
                "params": params,
                "permission_result": "EXECUTED",
            })
        except Exception:
            pass


_brain_instance = None

def _get_brain():
    global _brain_instance
    if _brain_instance is None:
        try:
            from llm.brain import Brain
            _brain_instance = Brain()
        except Exception as e:
            print(f"[PCAgent Dispatcher] Could not load local Brain: {e}")
    return _brain_instance


def _smart_fallback(action: str, original_text: str, params: dict) -> Tuple[bool, str]:
    """Last-resort handler: uses the local Brain LLM to interpret and execute the command."""
    try:
        # Primary fallback: use full Brain to parse the original text
        brain = _get_brain()
        if brain and original_text:
            try:
                import asyncio
                res = asyncio.run(brain.think(original_text))
                tool_name = res.get("tool")
                tool_params = res.get("params", {})
                resp = res.get("response", "")

                if tool_name and tool_name != "none":
                    handler = TOOL_MAP.get(tool_name)
                    if handler:
                        tool_res = handler(tool_params)
                        tool_res_str = str(tool_res) if tool_res else ""
                        if tool_res_str and len(tool_res_str) > len(resp):
                            return True, tool_res_str
                        return True, resp or tool_res_str or "Done, boss."
                elif resp:
                    return True, resp
            except Exception as b_err:
                print(f"[PCAgent Dispatcher] Brain fallback error: {b_err}, using rule fallbacks...")

        import subprocess
        import json as _json

        # Try to figure out the intent from the original text and execute it
        lower = original_text.lower()

        # File/folder creation patterns
        if any(w in lower for w in ("create", "make", "new")) and any(w in lower for w in ("folder", "directory")):
            # Extract folder name - take the last quoted or significant word
            words = original_text.split()
            name = params.get("name") or params.get("folder") or params.get("folder_name") or ""
            if not name:
                # Try to extract from text
                for i, w in enumerate(words):
                    if w.lower() in ("folder", "directory") and i > 0:
                        name = words[i - 1] if words[i - 1].lower() not in ("a", "the", "new", "create", "make") else ""
                    if w.lower() in ("called", "named") and i + 1 < len(words):
                        name = words[i + 1]
                        break
            if name:
                loc = "desktop" if "desktop" in lower else "downloads" if "download" in lower else "desktop"
                base = os.path.expanduser(f"~/{loc.title()}")
                os.makedirs(os.path.join(base, name), exist_ok=True)
                return True, f"Created folder '{name}' on your {loc}, sir."

        # File creation patterns
        if any(w in lower for w in ("create", "make", "new", "write")) and any(w in lower for w in ("file", "document", "note", "text")):
            name = params.get("name") or params.get("file") or params.get("filename") or "new_file.txt"
            content = params.get("content") or ""
            loc = "desktop" if "desktop" in lower else "downloads" if "download" in lower else "desktop"
            base = os.path.expanduser(f"~/{loc.title()}")
            with open(os.path.join(base, name), "w", encoding="utf-8") as f:
                f.write(content)
            return True, f"Created file '{name}' on your {loc}, sir."

        # Open/launch patterns
        if any(w in lower for w in ("open", "launch", "start", "run")):
            func = TOOL_MAP.get("open_app")
            if func:
                # Try to extract the app name from the text
                app_name = params.get("app") or params.get("app_name") or ""
                if not app_name:
                    for keyword in ("open", "launch", "start", "run"):
                        if keyword in lower:
                            idx = lower.index(keyword) + len(keyword)
                            rest = original_text[idx:].strip()
                            app_name = rest.split()[0] if rest else ""
                            break
                if app_name:
                    res = func({"app": app_name, "app_name": app_name})
                    return True, str(res)

        # Search patterns
        if any(w in lower for w in ("search", "google", "look up", "find online")):
            func = TOOL_MAP.get("web_search") or TOOL_MAP.get("search")
            if func:
                query = params.get("query") or original_text
                res = func({"query": query})
                return True, str(res)

        # Screenshot patterns
        if any(w in lower for w in ("screenshot", "screen capture", "capture screen", "screen shot")):
            try:
                from tools.screenshot import take_screenshot
                res = take_screenshot({})
                return True, str(res)
            except Exception:
                pass

        # Generic command execution via shell
        if any(w in lower for w in ("run command", "execute", "terminal", "cmd", "powershell")):
            cmd = params.get("command") or params.get("cmd") or ""
            if cmd:
                result = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=30)
                output = result.stdout.strip() or result.stderr.strip() or "Command completed."
                return result.returncode == 0, output[:500]

        print(f"[PCAgent Dispatcher] Smart fallback could not handle: action='{action}', text='{original_text}'")
        return False, f"I couldn't figure out how to do '{action}' on PC, boss. Try being more specific."

    except Exception as e:
        print(f"[PCAgent Dispatcher] Smart fallback error: {e}")
        return False, f"Failed to handle command on PC: {str(e)}"
