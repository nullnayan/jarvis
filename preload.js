// Exposes a small, safe IPC bridge from Electron's main process to the renderer.
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('jarvis', {
  onStateChange: (callback) => ipcRenderer.on('state-change', (_event, state) => callback(state)),
  onCaption: (callback) => ipcRenderer.on('set-caption', (_event, text) => callback(text)),
  onAmplitude: (callback) => ipcRenderer.on('set-amplitude', (_event, value) => callback(value)),
  onPersonaChange: (callback) => ipcRenderer.on('persona-change', (_event, persona) => callback(persona)),
  onHiddenChange: (callback) => ipcRenderer.on('set-hidden', (_event, hidden) => callback(hidden)),
  onFullscreenChange: (callback) => ipcRenderer.on('set-fullscreen-mode', (_event, isFullscreen) => callback(isFullscreen)),
  onUserSpeech: (callback) => ipcRenderer.on('user-speech', (_event, text) => callback(text)),
  onJarvisSpeech: (callback) => ipcRenderer.on('jarvis-speech', (_event, text) => callback(text)),
  onHandGesture: (callback) => ipcRenderer.on('hand-gesture', (_event, data) => callback(data)),
  onBackendStatus: (callback) => ipcRenderer.on('backend-status', (_event, status) => callback(status)),
  onApprovalRequest: (callback) => ipcRenderer.on('approval-request', (_event, value) => callback(value)),
  onPermissionRequest: (callback) => ipcRenderer.on('permission-request', (_event, value) => callback(value)),
  onSelfAudit: (callback) => ipcRenderer.on('self-audit', (_event, value) => callback(value)),
  onPlanProgress: (callback) => ipcRenderer.on('plan-progress', (_event, value) => callback(value)),
  onPhoneStatus: (callback) => ipcRenderer.on('phone-status', (_event, value) => callback(value)),
  sendPhoneConnect: (host, port, code) => ipcRenderer.send('phone-connect', host, port, code),
  sendPhoneDisconnect: () => ipcRenderer.send('phone-disconnect'),
  sendPhoneMirror: (action) => ipcRenderer.send('phone-mirror', action),
  sendPhoneScreencap: () => ipcRenderer.send('phone-screencap'),
  sendCommand: (text) => ipcRenderer.send('command', text),
  cancelAction: () => ipcRenderer.send('cancel-action'),
  sendApproval: (approved) => ipcRenderer.send('approval-response', approved),
  openFile: (filePath) => ipcRenderer.send('open-source-file', filePath),
  setSetting: (key, value) => ipcRenderer.send('settings-set', key, value),
  getSettings: () => ipcRenderer.send('settings-get'),
  onSettingsValues: (callback) => ipcRenderer.on('settings-values', (_event, values) => callback(values)),
  minimizeWindow: () => ipcRenderer.send('window-minimize'),
  hideWindow: () => ipcRenderer.send('window-hide'),
  restoreWindow: () => ipcRenderer.send('window-restore'),
  toggleFullscreen: () => ipcRenderer.send('toggle-fullscreen'),
  enterFullscreen: () => ipcRenderer.send('enter-fullscreen'),
  exitFullscreen: () => ipcRenderer.send('exit-fullscreen'),
  exitFullscreenToCorner: () => ipcRenderer.send('exit-fullscreen-to-corner'),
  toggleMic: (muted) => ipcRenderer.send('toggle-mic', muted),
  toggleTts: (muted) => ipcRenderer.send('toggle-tts', muted),
  closeWindow: () => ipcRenderer.send('window-close'),
});
